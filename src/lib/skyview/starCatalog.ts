// a totality-darkened sky, and nothing it could not: eclipse observing guides (Espenak) put the limit
// during totality at about +3.5, and the runtime fade (skyObjects.ts) keeps the last magnitude of that
// range down at whisper-faint, where it belongs.
//
// Source: HYG database v4.1 (astronexus/HYG-Database, CC BY-SA 4.0), filtered to `mag <= 3.5`. Unnamed
// secondary components of doubles are dropped (Capella B and the like sit at their primary's coordinates
// and would only be drawn twice); named ones are kept, so the first 93 entries match Wikipedia's list of
// the brightest stars exactly. Five faint southern stars with neither a proper name nor a Bayer letter
// (three in Carina, one each in Vela and Ophiuchus) are dropped rather than shown under a catalogue
// number no reader could look up.
//
// Positions are J2000. `scripts/build-sky.ts` precesses them to eclipse day and writes sky.generated.ts.
// This file is the checked-in SOURCE and is never regenerated by the build: a build must not depend on
// fetching a catalogue over the network.

